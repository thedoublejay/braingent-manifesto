"""Daily log: one Markdown file per day of what every agent did.

Agents only ever append one-line events to the ``## Log`` section of
``daily/YYYY-MM-DD.md``. The ``## Status`` block (ongoing, in review, blocked,
todo, done, spawned) is derived from those events and regenerated on every
write, so several CLIs can log concurrently without editing the same lines.
``## Goals`` belongs to the human and is never touched.

A new day's file carries over yesterday's unfinished items as ``carry-over``
events, so nothing silently drops off between days.
"""

from __future__ import annotations

import contextlib
import re
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, tzinfo
from pathlib import Path
from typing import IO, Any
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

try:
    import fcntl
except ImportError:  # pragma: no cover - Windows has no fcntl.
    fcntl = None  # type: ignore[assignment]

DAILY_DIR = "daily"
DEFAULT_SPRAWL_THRESHOLD = 10
CARRY_ACTOR = "carry-over"
STATUS_START = "<!-- braingent:daily-status:start -->"
STATUS_END = "<!-- braingent:daily-status:end -->"
LOG_HEADING = "## Log"
LOG_PATTERN = re.compile(r"^## Log[ \t]*\r?\n(.*?)(?=^## |\Z)", re.MULTILINE | re.DOTALL)
STATUS_PATTERN = re.compile(
    rf"^{re.escape(STATUS_START)}\r?\n## Status\r?\n.*?^{re.escape(STATUS_END)}(?=\r?$)",
    re.MULTILINE | re.DOTALL,
)

KINDS = ("todo", "started", "review", "blocked", "merged", "deployed", "verified", "done", "dropped", "spawned", "note")
BUCKET_OF = {
    "todo": "todo",
    "spawned": "todo",
    "started": "ongoing",
    "review": "review",
    "blocked": "blocked",
    "merged": "landed",
    "deployed": "landed",
    "verified": "done",
    "done": "done",
    "dropped": "done",
}
BUCKETS = (
    ("ongoing", "Ongoing"),
    ("review", "In review"),
    ("blocked", "Blocked"),
    ("landed", "Merged, not yet verified"),
    ("todo", "Todo"),
    ("done", "Done"),
)
UNFINISHED = ("ongoing", "review", "blocked", "landed", "todo")
NEVER_STALE = ("blocked",)
STALE_FILE = "stale.md"
STALE_HEADER = (
    "# Stale items\n\n"
    "<!-- Generated by braingent. Unfinished items nobody has touched for the configured number of days.\n"
    "     They are not done and not dropped. Log any event with the same ref to bring one back. -->\n\n"
)
STALE_PATTERN = re.compile(r"^- (\d{4}-\d{2}-\d{2}) · (\S+) · (\S+)(?: · epic:([a-z0-9][a-z0-9-]*))? · (.*)$")
SUFFIX_OF = {"dropped": " (dropped)", "merged": " (merged)", "deployed": " (deployed)", "verified": " (verified)"}
EVENT_PATTERN = re.compile(r"^- (\d{2}:\d{2}) · (\S+) · (\S+) · (\S+)(?: · epic:([a-z0-9][a-z0-9-]*))? · (.*)$")
TRAILING_EPIC_PATTERN = re.compile(r"^(.*?) · epic:(\S+)$")
EPIC_ID_PATTERN = re.compile(r"^epic--[a-z0-9][a-z0-9-]*?--([a-z0-9]+(?:-[a-z0-9]+)*)$")
EPIC_SLUG_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DAY_FILE_PATTERN = re.compile(r"^\d{4}-\d{2}-\d{2}\.md$")


@dataclass(frozen=True)
class Event:
    time: str
    actor: str
    kind: str
    ref: str | None
    text: str
    epic: str | None = None

    @property
    def key(self) -> str:
        return self.ref or self.text.strip().lower()

    def line(self) -> str:
        epic = f" · epic:{self.epic}" if self.epic else ""
        return f"- {self.time} · {self.actor} · {self.kind} · {self.ref or '-'}{epic} · {self.text}"


@dataclass
class EpicRollup:
    spawned: int = 0
    untouched: int = 0


@dataclass
class Status:
    buckets: dict[str, list[Event]] = field(default_factory=lambda: {name: [] for name, _ in BUCKETS})
    spawned: list[Event] = field(default_factory=list)
    spawned_untouched: int = 0
    carried: int = 0
    epics: dict[str, EpicRollup] = field(default_factory=dict)
    no_epic: EpicRollup = field(default_factory=EpicRollup)


def resolve_tz(name: str | None) -> tzinfo:
    if not name:
        return local_tz()
    try:
        return ZoneInfo(name)
    except (ZoneInfoNotFoundError, ValueError) as exc:
        raise ValueError(f"unknown timezone {name!r}; use an IANA name such as 'Asia/Singapore'") from exc


def local_tz() -> tzinfo:
    localtime = Path("/etc/localtime")
    if localtime.is_symlink():
        _, marker, key = localtime.resolve().as_posix().partition("zoneinfo/")
        if marker:
            with contextlib.suppress(ZoneInfoNotFoundError, ValueError):
                return ZoneInfo(key)
    local = datetime.now().astimezone().tzinfo
    assert local is not None
    return local


def day_path(root: Path, day: date) -> Path:
    return root / DAILY_DIR / f"{day.isoformat()}.md"


def human_date(day: date) -> str:
    return f"{day.day} {day:%B %Y}"


def clean(value: str) -> str:
    return " ".join(value.split())


def parse_events(text: str) -> list[Event]:
    events: list[Event] = []
    section = LOG_PATTERN.search(text)
    if section is None:
        return events
    for line in section.group(1).splitlines():
        match = EVENT_PATTERN.match(line)
        if match and match.group(3) in KINDS:
            time, actor, kind, ref, epic, body = match.groups()
            if epic is None and (trailing := TRAILING_EPIC_PATTERN.match(body)):
                body, epic = trailing.groups()
            events.append(Event(time, actor, kind, None if ref == "-" else ref, body, epic))
    return events


def derive_status(events: list[Event]) -> Status:
    latest: dict[str, tuple[int, Event]] = {}
    for index, event in enumerate(events):
        if event.kind != "note":
            latest[event.key] = (index, event)
    status = Status()
    for _, event in sorted(latest.values(), key=lambda pair: pair[0]):
        status.buckets[BUCKET_OF[event.kind]].append(event)
    status.spawned = [event for event in events if event.kind == "spawned"]
    status.spawned_untouched = sum(1 for _, event in latest.values() if event.kind == "spawned")
    status.carried = sum(1 for event in events if event.actor == CARRY_ACTOR)
    for event in status.spawned:
        rollup = status.epics.setdefault(event.epic, EpicRollup()) if event.epic else status.no_epic
        rollup.spawned += 1
    for _, event in latest.values():
        rollup = status.epics.setdefault(event.epic, EpicRollup()) if event.epic else status.no_epic
        if event.kind == "spawned":
            rollup.untouched += 1
    return status


def render_item(event: Event) -> str:
    ref = f"[{event.ref}] " if event.ref else ""
    suffix = SUFFIX_OF.get(event.kind, "")
    epic = f" · epic:{event.epic}" if event.epic else ""
    return f"- {ref}{event.text}{suffix} · {event.actor} · {event.time}{epic}"


def driving_epics(status: Status) -> str:
    ranked = sorted(status.epics.items(), key=lambda pair: (-pair[1].spawned, pair[0]))
    return ", ".join(f"{epic} ({rollup.spawned})" for epic, rollup in ranked if rollup.spawned)


def closed_today(status: Status) -> int:
    return sum(1 for event in status.buckets["done"] if event.actor != CARRY_ACTOR)


def render_status(status: Status, sprawl_threshold: int, stale: int = 0, outside_priorities: int | None = None) -> str:
    closed = closed_today(status)
    headline = (
        f"Spawned today: {len(status.spawned)} ({status.spawned_untouched} untouched) · Closed today: {closed} · "
        f"Net: {len(status.spawned) - closed:+d} · Carried over: {status.carried}"
    )
    if outside_priorities is not None:
        headline += f" · Spawned outside weekly priorities: {outside_priorities}"
    if stale:
        headline += f" · Stale: {stale} (see {DAILY_DIR}/{STALE_FILE})"
    lines = [
        STATUS_START,
        "## Status",
        "",
        "<!-- Generated from the log by braingent. Edits here are overwritten. -->",
        "",
        headline,
    ]
    if len(status.spawned) >= sprawl_threshold:
        lines += [
            "",
            f"> Sprawl: {len(status.spawned)} tickets or PRs spawned today (threshold {sprawl_threshold}). "
            "Triage these before starting new work.",
        ]
        if driving := driving_epics(status):
            lines.append(f"> Spawned by epic: {driving}.")
    sections = [(title, status.buckets[name]) for name, title in BUCKETS] + [("Spawned today", status.spawned)]
    for title, events in sections:
        lines += ["", f"### {title} ({len(events)})", ""]
        lines += [render_item(event) for event in events] or ["- None"]
    if status.epics or status.no_epic.spawned:
        lines += ["", f"### By epic ({len(status.epics)})", ""]
        lines += [
            f"- epic:{epic}: {rollup.spawned} spawned ({rollup.untouched} untouched)"
            for epic, rollup in sorted(status.epics.items())
        ]
        if status.no_epic.spawned:
            lines.append(f"- no epic: {status.no_epic.spawned} spawned ({status.no_epic.untouched} untouched)")
    lines.append(STATUS_END)
    return "\n".join(lines)


def with_status(text: str, sprawl_threshold: int, stale: int = 0, pinned: set[str] | None = None) -> str:
    status = derive_status(parse_events(text))
    outside = sum(1 for event in status.spawned if event.epic not in pinned) if pinned else None
    block = render_status(status, sprawl_threshold, stale, outside)
    section = LOG_PATTERN.search(text)
    existing = STATUS_PATTERN.search(text, 0, section.start() if section else len(text))
    if existing is not None:
        return f"{text[:existing.start()]}{block}{text[existing.end():]}"
    if section is None:
        return f"{text}\n\n{block}\n\n{LOG_HEADING}\n\n"
    return f"{text[:section.start()]}{block}\n\n{text[section.start():]}"


def previous_day_file(root: Path, day: date) -> Path | None:
    directory = root / DAILY_DIR
    if not directory.is_dir():
        return None
    earlier = sorted(
        path for path in directory.iterdir() if DAY_FILE_PATTERN.match(path.name) and path.stem < day.isoformat()
    )
    return earlier[-1] if earlier else None


def pinned_epics(root: Path, day: date) -> set[str]:
    """Epics named by this week's priorities; their items never go stale."""

    from braingent import weekly

    return weekly.priority_epics(root, day)


def stale_path(root: Path) -> Path:
    return root / DAILY_DIR / STALE_FILE


def parse_stale(text: str) -> list[tuple[str, Event]]:
    entries: list[tuple[str, Event]] = []
    for line in text.splitlines():
        if match := STALE_PATTERN.match(line):
            since, kind, ref, epic, body = match.groups()
            entries.append((since, Event("00:00", CARRY_ACTOR, kind, None if ref == "-" else ref, body, epic)))
    return entries


def read_stale(root: Path) -> list[tuple[str, Event]]:
    path = stale_path(root)
    if not path.is_file():
        return []
    with locked(path) as handle:
        return parse_stale(handle.read())


def stale_text(entries: list[tuple[str, Event]]) -> str:
    lines = [
        f"- {since} · {event.kind} · {event.ref or '-'}{' · epic:' + event.epic if event.epic else ''} · {event.text}"
        for since, event in sorted(entries, key=lambda pair: (pair[0], pair[1].key))
    ]
    return STALE_HEADER + "\n".join(lines) + ("\n" if lines else "")


def write_stale(root: Path, entries: list[tuple[str, Event]]) -> None:
    path = stale_path(root)
    if not entries and not path.exists():
        return
    with locked(path) as handle:
        rewrite(handle, stale_text(entries))


def recently_touched(root: Path, day: date, window_days: int) -> set[str]:
    """Keys with an event logged by an agent or person, not by carry-over, in the days before `day`."""

    directory = root / DAILY_DIR
    touched: set[str] = set()
    if not directory.is_dir():
        return touched
    earliest = (day - timedelta(days=window_days)).isoformat()
    for path in directory.iterdir():
        if DAY_FILE_PATTERN.match(path.name) and earliest <= path.stem < day.isoformat():
            with locked(path) as handle:
                touched.update(event.key for event in parse_events(handle.read()) if event.actor != CARRY_ACTOR)
    return touched


def carry_event(event: Event) -> Event:
    return Event("00:00", CARRY_ACTOR, "todo" if event.kind == "spawned" else event.kind, event.ref, event.text, event.epic)


def carried_events(root: Path, day: date, stale_after_days: int = 0, *, persist_stale: bool = True) -> list[Event]:
    source = previous_day_file(root, day)
    unfinished: list[Event] = []
    if source is not None:
        with locked(source) as handle:
            status = derive_status(parse_events(handle.read()))
        unfinished = [event for name in UNFINISHED for event in status.buckets[name]]
    if stale_after_days > 0:
        touched = recently_touched(root, day, stale_after_days)
        pinned = pinned_epics(root, day)

        def partition(entries: list[tuple[str, Event]]) -> tuple[list[Event], list[tuple[str, Event]]]:
            stale = {event.key: (since, event) for since, event in entries}
            keep: list[Event] = []
            known = {event.key for event in unfinished}
            for event in unfinished:
                fresh = event.key in touched or BUCKET_OF[event.kind] in NEVER_STALE or event.epic in pinned
                if fresh:
                    stale.pop(event.key, None)
                    keep.append(event)
                else:
                    stale.setdefault(event.key, (day.isoformat(), event))
            for key, (_, event) in list(stale.items()):
                if key not in known and event.epic in pinned:
                    keep.append(event)
                    del stale[key]
            return keep, list(stale.values())

        if persist_stale:
            with locked(stale_path(root)) as handle:
                unfinished, entries = partition(parse_stale(handle.read()))
                rewrite(handle, stale_text(entries))
        else:
            unfinished, _ = partition(read_stale(root))
    return [carry_event(event) for event in unfinished]


def new_day(root: Path, day: date, tz: tzinfo, stale_after_days: int = 0) -> str:
    carried = "\n".join(event.line() for event in carried_events(root, day, stale_after_days))
    return (
        f"# Daily log: {human_date(day)}\n\n"
        f"Timezone: {tz}\n\n"
        "## Goals\n\n"
        "<!-- Human-owned. Up to three outcomes for today. Agents never edit this section. -->\n\n"
        f"{LOG_HEADING}\n\n"
        "<!-- Append-only. One event per line: - HH:MM · agent · kind · ref [· epic:slug] · text -->\n"
        + (f"\n{carried}\n" if carried else "")
    )


@contextlib.contextmanager
def locked(path: Path) -> Iterator[IO[str]]:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.touch(exist_ok=True)
    with path.open("r+", encoding="utf-8", newline="") as handle:
        if fcntl is not None:
            fcntl.flock(handle, fcntl.LOCK_EX)
        else:
            import msvcrt

            msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
        try:
            yield handle
        finally:
            handle.flush()
            handle.seek(0)
            if fcntl is not None:
                fcntl.flock(handle, fcntl.LOCK_UN)
            else:
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)


def rewrite(handle: IO[str], text: str) -> None:
    handle.seek(0)
    handle.write(text)
    handle.truncate()


def update_day(
    root: Path, day: date, tz: tzinfo, sprawl_threshold: int, event: Event | None = None, stale_after_days: int = 0
) -> Path:
    path = day_path(root, day)
    with locked(path) as handle:
        text = handle.read() or new_day(root, day, tz, stale_after_days)
        rewrite_day(root, day, handle, text, sprawl_threshold, event)
    return path


def append_event(text: str, event: Event) -> str:
    section = LOG_PATTERN.search(text)
    if section is None:
        text += f"\n\n{LOG_HEADING}\n\n"
        section = LOG_PATTERN.search(text)
    assert section is not None
    end = section.end()
    separator = "" if text[:end].endswith("\n") else "\n"
    return f"{text[:end]}{separator}{event.line()}\n{text[end:]}"


def rewrite_day(root: Path, day: date, handle: IO[str], text: str, sprawl_threshold: int, event: Event | None) -> None:
    pinned = pinned_epics(root, day)
    if not stale_path(root).exists():
        text = append_event(text, event) if event else text
        rewrite(handle, with_status(text, sprawl_threshold, 0, pinned))
        return
    with locked(stale_path(root)) as stale_handle:
        entries = parse_stale(stale_handle.read())
        if event is not None:
            prior = next((stale_event for _, stale_event in entries if stale_event.key == event.key), None)
            if prior and event.kind == "note":
                text = append_event(text, carry_event(prior))
            text = append_event(text, event)
            entries = [(since, stale_event) for since, stale_event in entries if stale_event.key != event.key]
        rewrite(handle, with_status(text, sprawl_threshold, len(entries), pinned))
        rewrite(stale_handle, stale_text(entries))


def log_if_current(
    root: Path,
    day: date,
    expected: Event,
    replacement: Event,
    tz: tzinfo,
    sprawl_threshold: int = DEFAULT_SPRAWL_THRESHOLD,
    stale_after_days: int = 0,
) -> bool:
    if expected.key != replacement.key:
        raise ValueError("replacement must identify the same daily item")
    with locked(day_path(root, day)) as handle:
        text = handle.read() or new_day(root, day, tz, stale_after_days)
        latest = next((event for event in reversed(parse_events(text)) if event.key == expected.key), None)
        if latest != expected:
            return False
        rewrite_day(root, day, handle, text, sprawl_threshold, replacement)
        return True


def log_event(
    root: Path,
    kind: str,
    text: str,
    *,
    actor: str,
    ref: str | None = None,
    epic: str | None = None,
    now: datetime | None = None,
    tz: tzinfo | None = None,
    sprawl_threshold: int = DEFAULT_SPRAWL_THRESHOLD,
    stale_after_days: int = 0,
) -> Path:
    if kind not in KINDS:
        raise ValueError(f"unknown kind {kind!r}; use one of: {', '.join(KINDS)}")
    body = clean(text)
    if not body:
        raise ValueError("event text must not be empty")
    actor_value = "-".join(actor.split())
    if not actor_value:
        raise ValueError("event actor must not be empty")
    zone = tz or resolve_tz(None)
    moment = (now or datetime.now(zone)).astimezone(zone)
    ref_value = "-".join(ref.split()) if ref and ref.strip() else None
    event = Event(moment.strftime("%H:%M"), actor_value, kind, ref_value, body, normalise_epic(epic))
    return update_day(root, moment.date(), zone, sprawl_threshold, event, stale_after_days)


def normalise_epic(value: str | None) -> str | None:
    """Reduce an epic slug or `epic--<org>--<slug>` id to its slug."""

    if value is None or not value.strip():
        return None
    text = value.strip()
    if match := EPIC_ID_PATTERN.match(text):
        return match.group(1)
    if not EPIC_SLUG_PATTERN.match(text):
        raise ValueError(f"epic {value!r} must be a lowercase kebab-case slug or an epic-- id")
    return text


def refresh(
    root: Path, day: date, sprawl_threshold: int = DEFAULT_SPRAWL_THRESHOLD, tz: tzinfo | None = None, stale_after_days: int = 0
) -> Path:
    return update_day(root, day, tz or resolve_tz(None), sprawl_threshold, None, stale_after_days)


def summarise(
    root: Path, day: date, sprawl_threshold: int = DEFAULT_SPRAWL_THRESHOLD, tz: tzinfo | None = None, stale_after_days: int = 0
) -> dict[str, Any]:
    path = refresh(root, day, sprawl_threshold, tz, stale_after_days)
    with locked(path) as handle:
        status = derive_status(parse_events(handle.read()))

    def as_dict(event: Event) -> dict[str, Any]:
        return {
            "time": event.time,
            "actor": event.actor,
            "kind": event.kind,
            "ref": event.ref,
            "text": event.text,
            "epic": event.epic,
        }

    return {
        "date": day.isoformat(),
        "path": path.relative_to(root).as_posix(),
        "counts": {name: len(status.buckets[name]) for name, _ in BUCKETS},
        "items": {name: [as_dict(event) for event in status.buckets[name]] for name, _ in BUCKETS},
        "spawned": len(status.spawned),
        "spawned_untouched": status.spawned_untouched,
        "carried": status.carried,
        "closed": closed_today(status),
        "stale": len(read_stale(root)),
        "epics": {epic: {"spawned": rollup.spawned, "untouched": rollup.untouched} for epic, rollup in sorted(status.epics.items())},
        "no_epic": {"spawned": status.no_epic.spawned, "untouched": status.no_epic.untouched},
        "sprawl_threshold": sprawl_threshold,
        "sprawl": len(status.spawned) >= sprawl_threshold,
    }
